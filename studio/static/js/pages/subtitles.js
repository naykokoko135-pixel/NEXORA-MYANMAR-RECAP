import { api } from '../api.js';
import { h, icon, badge, act, emptyState, errorState, skeleton, confirmDialog, toast, fmtClock, parseClock, fmtDur, downloadUrl } from '../ui.js';
import { pageHead, card, kv, field, projectPicker, rememberProject } from '../comp.js';
import { safeMedia, enc } from './_util.js';

const EPS = 0.0005;

export default async function page(ctx) {
  const S = { pid: null, data: null, cues: [], snap: '', files: [], saving: false };
  const norm = (cues) => cues.map((c) => ({ start: c.start, end: c.end, my: c.my || '', en: c.en || '', sTxt: fmtClock(c.start), eTxt: fmtClock(c.end) }));
  const plain = () => JSON.stringify(S.cues.map((c) => [c.start, c.end, c.my, c.en]));
  const dirty = () => !!S.data && plain() !== S.snap;
  ctx.setDirty(dirty);
  const body = h('div');
  let alive = true, rows = [], activeIdx = -1, audio = null, captionMy, captionEn, errSummary, saveBtn, dirtyEl, shiftBtn;

  const picker = projectPicker(ctx, (id) => onSelect(id), { label: 'Project' });
  ctx.root.append(pageHead('Subtitle Studio', 'Edit cue timing and text. Ordering and overlaps are checked before you can save.'), h('div', { class: 'card' }, picker.el), h('div', { style: { height: '16px' } }), body);
  picker.ready.catch((e) => body.replaceChildren(errorState(e, () => location.reload())));

  async function onSelect(id) {
    if (id === S.pid && S.data) return;
    if (dirty()) {
      const ok = await confirmDialog({ title: 'Discard unsaved subtitle edits?', message: 'Switching project discards your unsaved cue changes.', confirmText: 'Discard' });
      if (!ok) { picker.select.value = S.pid || ''; rememberProject(S.pid); return; }
    }
    S.pid = id; S.data = null; S.cues = []; S.snap = '';
    if (!id) { body.replaceChildren(emptyState({ icon: 'captions', title: 'Select a project', text: 'Pick a project above to edit its subtitles.' })); return; }
    load();
  }

  async function load() {
    const pid = S.pid;
    body.replaceChildren(skeleton('rows', 6));
    try {
      const [d, f] = await Promise.all([api.get(`/api/projects/${enc(pid)}/subtitles`), api.get(`/api/projects/${enc(pid)}/files`).catch(() => ({ files: [] }))]);
      if (!alive || pid !== S.pid) return;
      S.files = f.files || [];
      setData(d); render();
    } catch (e) {
      if (!alive || pid !== S.pid || e.status === 401) return;
      body.replaceChildren(e.status === 404 ? emptyState({ icon: 'captions', title: 'No subtitles yet', text: 'This project has no subtitle cues. They are generated by the srt stage after the voice stage.', action: h('a', { class: 'btn', href: `#/renderer?project=${pid}` }, 'Open pipeline') }) : errorState(e, load));
    }
  }
  function setData(d) { S.data = d; S.cues = norm(d.cues || []); S.snap = plain(); }

  /* ---------- validation ---------- */
  function validate() {
    const per = [], dur = S.data?.duration;
    S.cues.forEach((c, i) => {
      const e = [], w = [];
      // Only re-parse a time when the user actually edited its text (keeps untouched cues byte-identical).
      const s = c.sTxt === fmtClock(c.start) ? c.start : parseClock(c.sTxt), en = c.eTxt === fmtClock(c.end) ? c.end : parseClock(c.eTxt);
      if (!isFinite(s)) e.push('Start time is invalid (use mm:ss.mmm).'); else c.start = s;
      if (!isFinite(en)) e.push('End time is invalid (use mm:ss.mmm).'); else c.end = en;
      if (isFinite(s) && isFinite(en) && en <= s) e.push('End must be after start.');
      const prev = S.cues[i - 1];
      if (prev && isFinite(s) && isFinite(prev.end)) {
        if (s < prev.start - EPS) e.push('Out of order: starts before the previous cue.');
        else if (s < prev.end - EPS) e.push(`Overlaps previous cue by ${(prev.end - s).toFixed(3)}s.`);
      }
      if (!c.my.trim() && !c.en.trim()) e.push('Both texts are empty.');
      if (dur && isFinite(en) && en > dur + 0.5) w.push(`Ends after the audio (${fmtClock(dur)}).`);
      per.push({ e, w });
    });
    return per;
  }

  /* ---------- table ---------- */
  function refresh() {
    const per = validate();
    let bad = 0;
    rows.forEach((r, i) => {
      const { e, w } = per[i];
      if (e.length) bad++;
      r.err.replaceChildren(...e.map((m) => h('span', { class: 'txt-err sm' }, m)), ...w.map((m) => h('span', { class: 'txt-warn sm' }, m)));
      r.tr.classList.toggle('cue-bad', e.length > 0);
      r.s.setAttribute('aria-invalid', String(e.length > 0)); r.e.setAttribute('aria-invalid', String(e.length > 0));
    });
    const d = dirty();
    dirtyEl.replaceChildren(d ? badge('Unsaved changes', 'warn') : badge('Saved', 'ok'), bad ? badge(`${bad} cue${bad === 1 ? '' : 's'} with errors`, 'err') : null);
    saveBtn.disabled = !ctx.canWrite || !d || bad > 0 || !S.cues.length || S.saving;
    if (shiftBtn) { shiftBtn.disabled = !ctx.canWrite || d; shiftBtn.title = d ? 'Save or revert your edits first: shifting applies to the saved cues.' : ''; }
    errSummary.textContent = bad ? `Fix ${bad} cue${bad === 1 ? '' : 's'} before saving.` : '';
    return bad;
  }

  function buildRow(c, i, redraw) {
    const s = h('input', { type: 'text', class: 'mono', inputmode: 'decimal', value: c.sTxt, 'aria-label': `Cue ${i + 1} start`, write: true, oninput: (e) => { c.sTxt = e.target.value; refresh(); } });
    const e = h('input', { type: 'text', class: 'mono', inputmode: 'decimal', value: c.eTxt, 'aria-label': `Cue ${i + 1} end`, write: true, oninput: (ev) => { c.eTxt = ev.target.value; refresh(); } });
    const my = h('textarea', { class: 'my', lang: 'my', rows: 2, value: c.my, 'aria-label': `Cue ${i + 1} Burmese`, write: true, oninput: (ev) => { c.my = ev.target.value; refresh(); } });
    const en = h('textarea', { lang: 'en', rows: 2, value: c.en, 'aria-label': `Cue ${i + 1} English`, write: true, oninput: (ev) => { c.en = ev.target.value; refresh(); } });
    const err = h('div', { class: 'cue-errs', 'aria-live': 'polite' });
    const act_ = h('div', { class: 'item-ctl' },
      h('button', { class: 'icon-btn sm', 'aria-label': `Play from cue ${i + 1}`, disabled: !audio || undefined, onclick: () => { audio.currentTime = Math.max(0, c.start || 0); audio.play().catch(() => {}); } }, icon('play', 14)),
      h('button', { class: 'icon-btn sm', write: true, 'aria-label': `Insert cue after ${i + 1}`, onclick: () => { const st = isFinite(c.end) ? c.end : 0; S.cues.splice(i + 1, 0, { start: st, end: st + 2, my: '', en: '', sTxt: fmtClock(st), eTxt: fmtClock(st + 2) }); redraw(); } }, icon('plus', 14)),
      h('button', { class: 'icon-btn sm', write: true, 'aria-label': `Delete cue ${i + 1}`, onclick: () => { S.cues.splice(i, 1); redraw(); } }, icon('trash', 14)));
    const tr = h('tr', { id: `cue-${i}` },
      h('td', { 'data-label': '#', class: 'c-i' }, String(i + 1)), h('td', { 'data-label': 'Start' }, s), h('td', { 'data-label': 'End' }, e),
      h('td', { 'data-label': 'Burmese' }, my), h('td', { 'data-label': 'English' }, en, err), h('td', { 'data-label': 'Actions' }, act_));
    rows.push({ tr, s, e, err });
    return tr;
  }
  function tableEl() {
    const tbody = h('tbody');
    const redraw = () => { rows = []; tbody.replaceChildren(...S.cues.map((c, i) => buildRow(c, i, redraw))); activeIdx = -1; refresh(); };
    const t = h('div', { class: 'tbl-wrap cue-wrap' }, h('table', { class: 'tbl edit cue-tbl' },
      h('thead', {}, h('tr', {}, ['#', 'Start', 'End', 'Burmese', 'English', 'Actions'].map((x) => h('th', { scope: 'col' }, x)))), tbody));
    t.redraw = redraw;
    return t;
  }

  /* ---------- audio sync ---------- */
  function syncCue() {
    if (!audio) return;
    const t = audio.currentTime;
    let idx = -1;
    for (let i = 0; i < S.cues.length; i++) { const c = S.cues[i]; if (isFinite(c.start) && isFinite(c.end) && t >= c.start && t < c.end) { idx = i; break; } }
    if (idx === activeIdx) return;
    rows[activeIdx]?.tr.classList.remove('cue-on');
    activeIdx = idx;
    if (idx >= 0) { rows[idx]?.tr.classList.add('cue-on'); if (!audio.paused) rows[idx]?.tr.scrollIntoView({ block: 'nearest' }); }
    captionMy.textContent = idx >= 0 ? S.cues[idx].my : ''; captionEn.textContent = idx >= 0 ? S.cues[idx].en : '';
  }

  /* ---------- actions ---------- */
  async function save() {
    if (refresh()) return;
    S.saving = true; refresh();
    const d = await act(() => api.put(`/api/projects/${enc(S.pid)}/subtitles`, { cues: S.cues.map((c) => ({ start: c.start, end: c.end, my: c.my, en: c.en })) }), { ok: 'Subtitles saved and SRT files rewritten' });
    S.saving = false;
    if (d) { await reloadFiles(); setData(d); render(); } else refresh();
  }
  async function reloadFiles() { try { S.files = (await api.get(`/api/projects/${enc(S.pid)}/files`)).files || []; } catch { /* keep old */ } }
  async function shift(secInput, btn) {
    const sec = Number(secInput.value);
    if (!isFinite(sec) || secInput.value === '') { toast('Enter the number of seconds to shift (negative moves earlier).', 'warn'); return; }
    if (sec === 0) { toast('A shift of 0 seconds changes nothing.', 'info'); return; }
    const ok = await confirmDialog({ title: 'Shift all cues?', message: `Every cue will move ${sec > 0 ? 'later' : 'earlier'} by ${Math.abs(sec)} second(s) and the SRT files will be rewritten.`, confirmText: 'Shift cues', danger: false });
    if (!ok) return;
    const d = await act(() => api.post(`/api/projects/${enc(S.pid)}/subtitles/shift`, { seconds: sec }), { btn, ok: `Shifted by ${sec}s` });
    if (d) { await reloadFiles(); setData(d); render(); }
  }

  function srtCard(label, s) {
    if (!s) return null;
    return h('div', { class: 'kv' }, h('span', {}, label), h('b', {}, h('span', {}, badge(s.ok ? 'Valid' : 'Issues', s.ok ? 'ok' : 'warn'), ` ${s.cues ?? 0} cues`)));
  }

  function render() {
    const d = S.data;
    rows = []; activeIdx = -1;
    const url = safeMedia(d.audio_url);
    audio = url ? h('audio', { controls: true, preload: 'metadata', src: url, 'aria-label': 'Narration audio' }) : null;
    captionMy = h('div', { class: 'c-my', lang: 'my' }); captionEn = h('div', { class: 'c-en' });
    errSummary = h('span', { class: 'txt-err sm', role: 'alert' }); dirtyEl = h('span', { class: 'row' });
    saveBtn = h('button', { class: 'btn primary', write: true, onclick: save }, icon('save', 16), 'Save subtitles');
    const tbl = tableEl();
    const secs = h('input', { type: 'number', step: '0.1', id: 'shift', 'aria-label': 'Shift seconds', placeholder: 'e.g. -0.5', write: true });
    shiftBtn = h('button', { class: 'btn', write: true, onclick: (e) => shift(secs, e.currentTarget) }, icon('clock', 16), 'Shift all');
    const srtFiles = S.files.filter((f) => f.kind === 'srt_en' || f.kind === 'srt_my');

    body.replaceChildren(
      h('div', { class: 'grid split' },
        card('Preview', h('div', { class: 'stack' },
          audio || h('div', { class: 'banner info' }, icon('info'), h('div', {}, 'No narration audio exists for this project yet, so timing cannot be previewed. Run the voice stage first.')),
          h('div', { class: 'caption-box', 'aria-live': 'off' }, captionMy, captionEn, h('span', { class: 'faint sm' }, 'Current cue appears here during playback')))),
        card('Details & export', h('div', {}, kv('Cues', S.cues.length), kv('Audio duration', d.duration != null ? fmtDur(d.duration) : '—'), srtCard('English SRT', d.srt?.en), srtCard('Burmese SRT', d.srt?.my),
          h('div', { class: 'stack sm', style: { marginTop: '10px' } }, h('p', { class: 'lbl-s' }, 'Download SRT'),
            srtFiles.length ? srtFiles.map((f) => h('a', { class: 'btn sm', href: downloadUrl(f), download: f.name }, icon('download', 14), `${f.kind === 'srt_en' ? 'English' : 'Burmese'} · ${f.name}`)) : h('p', { class: 'muted sm' }, 'No SRT files exist yet.'),
            h('p', { class: 'faint sm' }, 'Downloads are the files last saved on the server.'))))),
      [d.srt?.en, d.srt?.my].some((s) => s?.issues?.length) ? h('div', { class: 'banner warn', style: { marginTop: '16px' } }, icon('alert'), h('div', {}, h('b', {}, 'SRT issues reported by the server: '), ['en', 'my'].flatMap((k) => (d.srt?.[k]?.issues || []).map((m) => `${k.toUpperCase()}: ${m}`)).join(' · '))) : null,
      h('div', { style: { height: '16px' } }),
      card('Cues', S.cues.length ? tbl : emptyState({ icon: 'captions', title: 'No cues', text: 'Add a cue to start.', action: h('button', { class: 'btn', write: true, onclick: () => { S.cues.push({ start: 0, end: 2, my: '', en: '', sTxt: fmtClock(0), eTxt: fmtClock(2) }); render(); } }, icon('plus', 16), 'Add cue') }),
        { actions: h('div', { class: 'row' }, h('label', { class: 'sr-only', for: 'shift' }, 'Shift seconds'), secs, shiftBtn,
          h('button', { class: 'btn', write: true, onclick: () => { const l = S.cues[S.cues.length - 1]; const st = l && isFinite(l.end) ? l.end : 0; S.cues.push({ start: st, end: st + 2, my: '', en: '', sTxt: fmtClock(st), eTxt: fmtClock(st + 2) }); tbl.redraw ? (S.cues.length === 1 ? render() : tbl.redraw()) : render(); } }, icon('plus', 16), 'Add cue')) }),
      h('div', { class: 'sticky-bar' }, h('div', { class: 'row' }, dirtyEl, errSummary), h('div', { class: 'row' },
        h('button', { class: 'btn', onclick: () => { setDataKeep(); render(); } }, icon('refresh', 16), 'Revert'), saveBtn)));
    if (S.cues.length) tbl.redraw();
    if (audio) { audio.addEventListener('timeupdate', syncCue); audio.addEventListener('seeked', syncCue); }
    refresh();
  }
  function setDataKeep() { S.cues = norm(S.data.cues || []); S.snap = plain(); }

  return { destroy() { alive = false; try { audio?.pause(); } catch { /* ignore */ } } };
}
