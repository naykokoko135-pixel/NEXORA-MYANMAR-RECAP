"""Free, source-tracking worksheet for movie recap research.

This module does not browse the web or invent movie facts. It helps the
creator record and verify information before writing an original recap.
"""


def generate_research_worksheet(topic: str) -> str:
    title = " ".join((topic or "").split()).strip() or "[ဇာတ်ကားအမည်]"
    return f"""🔎 NEXORA — Movie Research Worksheet

ဇာတ်ကား: {title}

မှတ်ချက်: ဤအခမဲ့ worksheet သည် အင်တာနက်မှ အလိုအလျောက် ရှာဖွေခြင်း မလုပ်ပါ။ အောက်ပါအချက်များကို ယုံကြည်ရသော အရင်းအမြစ်များဖြင့် ကိုယ်တိုင်စစ်ဆေးပြီး ဖြည့်ပါ။

၁။ အခြေခံအချက်အလက်
- မူရင်းခေါင်းစဉ်:
- ထွက်ရှိသည့်နှစ်:
- ဒါရိုက်တာ:
- အမျိုးအစား:
- နိုင်ငံ/ဘာသာစကား:
- အဓိကသရုပ်ဆောင်များ:

၂။ ဇာတ်လမ်းအချက်အလက် စစ်ဆေးရန်
- ဇာတ်လမ်းဖြစ်ပွားရာ နေရာ/ကာလ:
- အဓိကဇာတ်ကောင်နှင့် ရည်ရွယ်ချက်:
- အစပိုင်းပဋိပက္ခ:
- အရေးကြီးဖြစ်ရပ်များ:
- အလှည့်အပြောင်း:
- Climax:
- အဆုံးသတ်:
- မသေချာသေးသော အချက်များ:

၃။ Source မှတ်တမ်း
Source ၁
- ဝက်ဘ်ဆိုက်/စာအုပ်/အင်တာဗျူး:
- URL သို့မဟုတ် ကိုးကားချက်:
- ထုတ်ဝေသူ/ရေးသားသူ:
- စစ်ဆေးသည့်နေ့:
- အတည်ပြုနိုင်သည့်အချက်:

Source ၂
- ဝက်ဘ်ဆိုက်/စာအုပ်/အင်တာဗျူး:
- URL သို့မဟုတ် ကိုးကားချက်:
- ထုတ်ဝေသူ/ရေးသားသူ:
- စစ်ဆေးသည့်နေ့:
- အတည်ပြုနိုင်သည့်အချက်:

၄။ အချက်အလက်စစ်ဆေးမှု
[ ] အခြေခံအချက်အလက်ကို အနည်းဆုံး ယုံကြည်ရသော source ဖြင့် စစ်ဆေးပြီးပြီ။
[ ] အရေးကြီးဇာတ်ကွက်များကို source တစ်ခုထက်ပို၍ နှိုင်းယှဉ်ပြီးပြီ။
[ ] မတူညီသော အချက်အလက်များကို မှတ်သားထားပြီးပြီ။
[ ] မသေချာသောအချက်ကို အမှန်ဟု မရေးထားပါ။
[ ] မူရင်း dialogue၊ screenplay သို့မဟုတ် အခြားသူ၏ recap ကို မကူးထားပါ။

၅။ Recap မရေးမီ
- ကြည့်ရှုသူ သိထားသင့်သည့် နောက်ခံ:
- ကိုယ်ပိုင်ရှင်းပြချက်/သုံးသပ်ချက်:
- ကိုယ်ပိုင် Hook မေးခွန်း:
- နောက်ဆုံးပေးလိုသည့် အမြင်:

နောက်တစ်ဆင့်: အတည်ပြုပြီးသော မှတ်စုများကို အသုံးပြုပြီး /create {title} ဖြင့် Recap worksheet ထုတ်ပါ။ ဇာတ်လမ်းအသေးစိတ်ကို ကိုယ်ပိုင်စကားဖြင့် ရေးပြီး မူရင်းရုပ်ရှင်ကို အစားထိုးကြည့်ရှုနိုင်လောက်အောင် မပြုလုပ်ပါနှင့်။
"""


def format_research_notes(topic: str, notes: str) -> str:
    title = " ".join((topic or "").split()).strip() or "[ဇာတ်ကားအမည်]"
    clean_notes = (notes or "").strip()
    if not clean_notes:
        raise ValueError("မှတ်စုစာသား မပါဝင်သေးပါ။")
    if len(clean_notes) > 12000:
        raise ValueError("မှတ်စုသည် ရှည်လွန်းနေပါသည်။ ၁၂,၀၀၀ အက္ခရာအောက် ခွဲပို့ပါ။")
    return (
        f"📝 NEXORA — သင့် Research Notes\nဇာတ်ကား: {title}\n\n"
        "အောက်ပါအကြောင်းအရာသည် သင်ပေးထားသော မှတ်စုများကိုသာ စုစည်းထားခြင်းဖြစ်ပြီး "
        "အချက်အလက်မှန်ကန်ကြောင်း NEXORA က သီးခြားအတည်မပြုထားပါ။\n\n"
        f"{clean_notes}\n\n"
        "အသုံးမပြုမီ source များနှင့် ပြန်စစ်ဆေးပါ။"
    )
